"""
Shared approval gate and audit log for RAIN action packages.

A package builder (one per persona) returns a dict with a stable `package_id`
and a list of `actions`; each action has an `action_id`, `type`, `patient_id`,
`status` ("ready" or "needs_input"), `needs` and a `draft`. This module adds
what every package needs:

  * finalize()  folds in what has already been routed and computes the state
                and the counts the card shows
  * decide()    records a person's route / hold decision
  * audit()     every decision: who, when, what was routed, what was held

DRAFT-ONLY. Routing marks ready actions as routed and writes an audit entry;
nothing is ever sent to an external system (delivery is always "simulated").
This module has no network code. Each action is routed at most once, enforced
by the database primary key, so a double click or two simultaneous requests
cannot duplicate it. The audit log is two Postgres tables (decisions,
routed_actions). A scope key keeps packages and tests apart; the default
scope is RAIN_ACTION_LOG, or "action_log" when that is unset.
"""

import json
import os
import threading
from datetime import datetime, timezone

import pg_compat

LOG_PATH = os.environ.get("RAIN_ACTION_LOG", "action_log")
DELIVERY = "simulated"
_LOCK = threading.Lock()


class ActionInputError(ValueError):
    """A caller-supplied value is missing or invalid (the API returns 400)."""


def log_scope(path=None):
    return path or LOG_PATH


def log_conn():
    """Postgres connection with the audit tables present. `scope` on each
    row is what used to be a separate SQLite file."""
    c = pg_compat.connect()
    c.execute(
        "CREATE TABLE IF NOT EXISTS decisions ("
        "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
        "scope TEXT NOT NULL, package_id TEXT NOT NULL, decision TEXT NOT NULL, "
        "decided_by TEXT NOT NULL, decided_at TEXT NOT NULL, note TEXT, "
        "inputs_json TEXT, routed_json TEXT, held_json TEXT, delivery TEXT NOT NULL)"
    )
    c.execute(
        "CREATE TABLE IF NOT EXISTS routed_actions ("
        "scope TEXT NOT NULL, action_id TEXT NOT NULL, package_id TEXT NOT NULL, "
        "decision_id INTEGER NOT NULL, routed_at TEXT NOT NULL, routed_by TEXT NOT NULL, "
        "draft_json TEXT NOT NULL, PRIMARY KEY (scope, action_id))"
    )
    c.commit()
    return c


def routed_snapshots(package_id, log_path=None):
    """What has been routed for this package, and the last decision."""
    scope = log_scope(log_path)
    with _LOCK:
        lc = log_conn()
        try:
            rows = lc.execute(
                "SELECT action_id, routed_at, routed_by, draft_json FROM routed_actions WHERE package_id = ? AND scope = ?",
                (package_id, scope),
            ).fetchall()
            last = lc.execute(
                "SELECT decision, decided_by, decided_at FROM decisions WHERE package_id = ? AND scope = ? ORDER BY id DESC LIMIT 1",
                (package_id, scope),
            ).fetchone()
        finally:
            lc.close()
    return ({r[0]: {"routed_at": r[1], "routed_by": r[2], "draft": json.loads(r[3])} for r in rows},
            {"decision": last[0], "decided_by": last[1], "decided_at": last[2]} if last else None)


def finalize(pkg, log_path=None, types=()):
    """Fold in routed state; add `state`, `last_decision`, per-type counts and the aggregated needs."""
    snaps, last = routed_snapshots(pkg["package_id"], log_path)
    actions = pkg["actions"]
    for a in actions:
        s = snaps.get(a["action_id"])
        a["routed"] = bool(s)
        a["routed_at"] = s["routed_at"] if s else None
        a.setdefault("needs", [])
        if s:
            a["status"], a["draft"], a["needs"] = "routed", s["draft"], []
    routed_n = sum(a["routed"] for a in actions)
    pkg["state"] = ("routed" if actions and routed_n == len(actions) else "partially_routed" if routed_n
                    else "held" if last and last["decision"] == "hold" else "draft")
    pkg["last_decision"] = last
    pkg["delivery"] = DELIVERY

    summary = pkg.setdefault("summary", {})
    for t in types:
        xs = [a for a in actions if a["type"] == t]
        summary[t] = {"total": len(xs), "ready": sum(a["status"] == "ready" for a in xs),
                      "needs_input": sum(a["status"] == "needs_input" for a in xs), "routed": sum(a["routed"] for a in xs)}
    summary.update({"actions_total": len(actions), "ready_total": sum(a["status"] == "ready" for a in actions), "routed_total": routed_n})

    needs, seen = [], {}
    for a in actions:
        for nd in a["needs"]:
            k = nd["field"]
            if k not in seen:
                seen[k] = {"field": k, "label": nd["label"], "why": nd["why"], "action_ids": []}
                needs.append(seen[k])
            seen[k]["action_ids"].append(a["action_id"])
    for k in needs:
        k["count"] = len(k["action_ids"])
    pkg["needs_input"] = needs
    return pkg


def decide(build, decision, decided_by, inputs=None, note=None, log_path=None):
    """Record a person's decision. 'route' marks every READY action as routed (simulated);
    'hold' routes nothing. Anything not ready stays held. Nothing is ever sent."""
    if decision not in ("route", "hold"):
        raise ActionInputError("decision must be 'route' or 'hold'")
    who = (decided_by or "").strip()
    if not who or len(who) > 80:
        raise ActionInputError("decided_by is required (1-80 characters) so every decision is attributable")
    note = (note or "").strip()[:500] or None

    pkg = build(inputs, log_path)                     # validates inputs
    routable = [a for a in pkg["actions"] if decision == "route" and a["status"] == "ready"]
    already = [a["action_id"] for a in pkg["actions"] if a["routed"]]
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    brief = lambda xs: [{"action_id": a["action_id"], "type": a["type"], "patient_id": a["patient_id"]} for a in xs]
    held_of = lambda xs: [dict(x, needs=[n["field"] for n in a["needs"]]) for x, a in zip(brief(xs), xs)]

    # Each action is routed at most once. The primary key on routed_actions is the real guard
    # (it also holds across several server processes); the lock only keeps threads tidy.
    # What was ACTUALLY routed is what gets logged.
    scope = log_scope(log_path)
    with _LOCK:
        lc = log_conn()
        try:
            cur = lc.execute(
                "INSERT INTO decisions (scope, package_id, decision, decided_by, decided_at, note, inputs_json, routed_json, held_json, delivery) "
                "VALUES (?,?,?,?,?,?,?,?,?,?) RETURNING id",
                (scope, pkg["package_id"], decision, who, now, note, json.dumps(inputs or {}), "[]", "[]", DELIVERY),
            )
            did, routed_now = cur.fetchone()[0], []
            for a in routable:
                ins = lc.execute(
                    "INSERT INTO routed_actions (scope, action_id, package_id, decision_id, routed_at, routed_by, draft_json) "
                    "VALUES (?,?,?,?,?,?,?) ON CONFLICT (scope, action_id) DO NOTHING",
                    (scope, a["action_id"], pkg["package_id"], did, now, who, json.dumps(a["draft"])),
                )
                if ins.rowcount == 1:
                    routed_now.append(a)
                else:
                    already.append(a["action_id"])       # another request routed it first
            held = [a for a in pkg["actions"] if a["action_id"] not in already and a not in routed_now]
            lc.execute(
                "UPDATE decisions SET routed_json = ?, held_json = ? WHERE id = ? AND scope = ?",
                (json.dumps(brief(routed_now)), json.dumps(held_of(held)), did, scope),
            )
            lc.commit()
        finally:
            lc.close()

    if decision == "hold":
        message = "Held. Nothing was routed; the package stays a draft and can be routed later."
    elif routed_now:
        message = (f"Recorded your approval of {len(routed_now)} action(s). Simulated: nothing was sent to any program, dispatcher, clinic or care team."
                   + (f" {len(held)} action(s) are held until their missing input is supplied." if held else ""))
    else:
        message = "No action was ready to route, so nothing was recorded as routed."
    return {"decision": decision, "package_id": pkg["package_id"], "decided_by": who, "decided_at": now, "delivery": DELIVERY,
            "message": message, "routed": brief(routed_now), "already_routed": already, "held": held_of(held), "package": build(None, log_path)}


def audit(build, log_path=None):
    package_id = build(None, log_path)["package_id"]
    scope = log_scope(log_path)
    with _LOCK:
        lc = log_conn()
        try:
            ds = lc.execute(
                "SELECT id, decision, decided_by, decided_at, note, routed_json, held_json, delivery "
                "FROM decisions WHERE package_id = ? AND scope = ? ORDER BY id",
                (package_id, scope),
            ).fetchall()
        finally:
            lc.close()
    return {"package_id": package_id, "delivery": DELIVERY,
            "decisions": [{"id": d[0], "decision": d[1], "decided_by": d[2], "decided_at": d[3], "note": d[4],
                           "routed": json.loads(d[5]), "held": json.loads(d[6]), "delivery": d[7]} for d in ds]}
