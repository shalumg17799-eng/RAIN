"""Generic runtime for any App Pack: one FastAPI service + one HTML page.

    python -m factory serve --app <app_id>          # local
    (the same module is the container entry point on Azure)

Dashboard figures are computed live from the metric layer on every request;
questions go through the governed insights layer under the persona's own
Postgres role and row-level security. Nothing here is specific to one app."""
from __future__ import annotations

import base64
import json
import logging
import os
import sys
import time
import uuid
from functools import lru_cache
from pathlib import Path

import yaml
from fastapi import FastAPI, HTTPException, Request
from fastapi.responses import HTMLResponse
from pydantic import BaseModel

from factory.apppack import AppPack
from factory.config import ROOT
from factory.tools.db import scalar

sys.path.insert(0, str(ROOT))
log = logging.getLogger("factory.runtime")


def fmt(value, unit: str) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, str):
        return value
    v = float(value)
    if unit in ("percent", "rate"):
        return f"{v:g}%"
    if unit == "currency":
        return f"${v / 1e6:.1f}M" if abs(v) >= 1e6 else f"${v:,.0f}"
    if unit == "count" or v.is_integer():
        return f"{int(round(v)):,}"
    return f"{v:,.1f}"


def signed_in_groups(request: Request) -> set[str] | None:
    """Entra ID groups of the signed-in user, from Container Apps built-in authentication
    (X-MS-CLIENT-PRINCIPAL). None when sign-in is not enabled (FACTORY_AUTH != entra)."""
    if os.environ.get("FACTORY_AUTH", "").lower() != "entra":
        return None
    raw = request.headers.get("X-MS-CLIENT-PRINCIPAL")
    if not raw:
        raise HTTPException(401, "sign-in required")
    try:
        principal = json.loads(base64.b64decode(raw))
    except Exception:
        raise HTTPException(401, "unreadable sign-in principal") from None
    return {c["val"] for c in principal.get("claims", []) if c.get("typ") in ("groups", "roles")}


class Ask(BaseModel):
    persona: str
    question: str


def create_app(app_id: str, enable_ask: bool = True) -> FastAPI:
    pack = AppPack(app_id)
    manifest = pack.manifest()
    ui = pack.read_json("ui.json")
    if ui is None:
        raise RuntimeError("ui.json missing: run agent 4 (app builder) first")
    metrics = {m.id: m for m in pack.metrics().metrics}
    # access.yaml maps each persona to the Entra group (or app role) ids allowed to use it.
    access = yaml.safe_load(pack.path("access.yaml").read_text(encoding="utf-8")) if pack.path("access.yaml").is_file() else {}

    def allowed_personas(request: Request) -> set[str]:
        groups = signed_in_groups(request)
        everyone = {p["id"] for p in ui["personas"]}
        if groups is None:
            return everyone            # local / demo mode: persona chosen on the page
        return {p for p in everyone if groups & set(access.get(p, []))}

    def require(request: Request, persona: str) -> None:
        if persona not in allowed_personas(request):
            raise HTTPException(403, f"you are not allowed to use the {persona} view")
    kpis = {k.id: k for k in manifest.kpis}
    signals = {s.id: s for s in manifest.signals}
    app = FastAPI(title=f"{manifest.app.name} (generated by the PRD-to-App Factory)")

    @app.middleware("http")
    async def tag(request: Request, call_next):
        start = time.perf_counter()
        response = await call_next(request)
        response.headers["X-Factory-App"] = app_id
        if request.url.path.startswith("/api"):
            log.info("%s %s -> %d (%.0f ms)", request.method, request.url.path, response.status_code,
                     (time.perf_counter() - start) * 1000)
        return response

    def live(metric_id: str):
        m = metrics.get(metric_id)
        if m is None:
            return None, "missing"
        if not m.sql:
            return m.value, "static"
        try:
            return scalar(app_id, m.sql), "live"
        except Exception as exc:
            log.warning("metric %s failed: %s", metric_id, exc)
            return None, "error"

    @app.get("/", response_class=HTMLResponse)
    def index():
        return (Path(__file__).parent / "index.html").read_text(encoding="utf-8")

    @app.get("/api/app")
    def app_info(request: Request):
        mine = allowed_personas(request)
        return {"id": app_id, "name": manifest.app.name, "description": manifest.app.description,
                "title": ui.get("title", manifest.app.name), "subtitle": ui.get("subtitle", ""),
                "personas": [{"id": p["id"], "label": p.get("label", p["id"])} for p in ui["personas"] if p["id"] in mine],
                "ask_enabled": enable_ask}

    @app.get("/api/personas/{persona}/dashboard")
    def dashboard(persona: str, request: Request):
        require(request, persona)
        cfg = next((p for p in ui["personas"] if p["id"] == persona), None)
        if cfg is None:
            raise HTTPException(404, f"unknown persona {persona}")
        tiles = []
        for kid in cfg.get("kpis", []):
            k = kpis.get(kid)
            if not k:
                continue
            value, source = live(kid)
            tiles.append({"id": kid, "label": k.label, "value": fmt(value, k.unit), "prd": k.value,
                          "prior": k.prior, "source": source, "definition": k.definition})
        cards = []
        for sid in cfg.get("signals", []):
            s = signals.get(sid)
            if not s:
                continue
            value, source = live(sid) if s.headline is not None else (None, "none")
            subs = []
            for f in s.sub_figures:
                v, src = live(f"{sid}.{f.name}")
                subs.append({"name": f.description or f.name.replace("_", " "), "value": fmt(v, f.unit),
                             "prd": fmt(f.value, f.unit), "source": src})
            cards.append({"id": sid, "title": s.title, "severity": s.severity, "description": s.description,
                          "headline": fmt(value, s.unit) if s.headline is not None else None,
                          "source": source, "sub_figures": subs})
        return {"persona": persona, "label": cfg.get("label", persona), "intro": cfg.get("intro", ""),
                "tiles": tiles, "signals": cards, "questions": cfg.get("questions", [])}

    @lru_cache(maxsize=1)
    def insights_state():
        from insights.api.app import ServerState
        from insights.api.settings import ServerSettings
        env = dict(os.environ)
        env["INSIGHTS_APPS_DIR"] = str(pack.path("insights"))
        env["INSIGHTS_API_KEYS_FILE"] = str(pack.path("insights", "keys.local.yaml"))
        env.setdefault("INSIGHTS_LLM_PROVIDER", "anthropic")
        return ServerState(ServerSettings.from_env(env))

    @app.post("/api/ask")
    def ask(body: Ask, request: Request):
        require(request, body.persona)
        if not enable_ask:
            raise HTTPException(503, "questions are disabled in this preview")
        from insights.api.app import build_response
        from insights.api.auth import KeysFile, principal_for
        from insights.contracts.request import AskContext, AskRequest
        state = insights_state()
        served = state.apps.get(app_id)
        role = f"{app_id}_{body.persona}"[:63]
        keys = KeysFile.model_validate(yaml.safe_load(pack.path("insights", "keys.local.yaml").read_text()))
        record = next((k for k in keys.keys if role in k.roles), None)
        if served is None or record is None:
            raise HTTPException(403, "this persona has no access to questions")
        # The persona was checked against the signed-in user's Entra groups above (FACTORY_AUTH=entra);
        # the server then acts with that persona's key record, never with anything from the body.
        principal = principal_for(record, served.profile)
        request_id = uuid.uuid4()
        req = AskRequest(request_id=request_id, query=body.question, context=AskContext())
        run = state.runtime.run(served.agent, input={"request_id": str(request_id), "query": body.question,
                                                     "context": req.context.model_dump(exclude_none=True)},
                                principal=principal, app=served.profile, options=req.options,
                                conversation_id=None, trace_id=uuid.uuid4().hex)
        res = build_response(request_id, run, state.results, principal).model_dump(mode="json")
        return {"status": res.get("status"), "narrative": res.get("narrative"),
                "reason": (res.get("reason") or {}).get("message"), "data": res.get("data"),
                "sql": (res.get("query") or {}).get("sql"), "assumptions": res.get("assumptions") or []}

    @app.get("/health")
    def health():
        return {"status": "ok", "app": app_id}

    return app


def main() -> None:
    import uvicorn
    app_id = os.environ.get("FACTORY_APP") or (sys.argv[1] if len(sys.argv) > 1 else None)
    if not app_id:
        raise SystemExit("usage: python -m factory.runtime_app.server <app_id>  (or FACTORY_APP)")
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)-7s [%(name)s] %(message)s")
    uvicorn.run(create_app(app_id), host=os.environ.get("HOST", "0.0.0.0"), port=int(os.environ.get("PORT", "8080")))


if __name__ == "__main__":
    main()
