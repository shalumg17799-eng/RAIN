COUNTY_SQL = """SELECT p.locationname AS county, p.measure, p.data_value,
       s.rpl_themes AS svi_percentile, r.value AS rucc_code
FROM public_data.cdc_places p
LEFT JOIN public_data.svi_county s
       ON s.county = p.locationname || ' County' AND s.st_abbr = p.stateabbr
LEFT JOIN public_data.rucc_county r ON r.fips = s.fips AND r.attribute = 'RUCC_2023'
WHERE p.measureid = %s AND p.stateabbr = %s AND p.data_value_type = 'Crude prevalence'
ORDER BY p.data_value DESC"""


def write_api(out_path, schemas=("synthetic", "public_data")):
    import psycopg2

    conn = psycopg2.connect(dsn())
    with conn, conn.cursor() as cur:
        cur.execute("""SELECT table_schema, table_name, column_name
                       FROM information_schema.columns
                       WHERE table_schema = ANY(%s)
                       ORDER BY table_schema, table_name, ordinal_position""", (list(schemas),))
        tables = {}
        for sch, tab, col in cur.fetchall():
            tables.setdefault(sch, {}).setdefault(tab, []).append(col)
    conn.close()
    if not any(tables.values()):
        raise SystemExit(f"no tables found in schemas {schemas}; load data first")
    pub = tables.get("public_data", {})
    has_overview = all(t in pub for t in ("cdc_places", "svi_county", "rucc_county"))
    out_path.write_text(MODULE_TEMPLATE.format(schemas=" + ".join(schemas), tables=tables,
                                               county_overview=COUNTY_SQL if has_overview else ""),
                        encoding="utf-8")
    n = sum(len(t) for t in tables.values())
    print(f"wrote {out_path} ({n} table endpoints + /tables"
          + (" + /views/county-overview)" if has_overview else ")"))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--prd", default=str(ROOT / "doc/prd/RAIN_Platform_PRD_v0.2_factory_extract.txt"))
    ap.add_argument("--ddl", default=str(ROOT / "doc/prd/RAIN_Platform_PRD_v0.2_planned_schemas.sql"))
    ap.add_argument("--rows", type=int, default=200)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--api-out", default=str(ROOT / "rain-api/data_api.py"))
    ap.add_argument("--skip-load", action="store_true", help="only regenerate the router")
    a = ap.parse_args()
    if not a.skip_load:
        load(generate(Path(a.prd), Path(a.ddl), a.rows, a.seed))
    write_api(Path(a.api_out))
