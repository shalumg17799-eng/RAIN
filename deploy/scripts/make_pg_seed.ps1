# Regenerate the Postgres seed for the docker stack from the LIVE local database.
# Produces deploy/initdb/01-roles.sql (rain_app + insights_* roles and memberships) and
# deploy/initdb/02-rain.sql (schema + data + grants + RLS policies + masked-view schemas).
# Both are gitignored: the data seed is derived, never source. Run from the repo root:
#   $env:PGPASSWORD="<postgres superuser pw>"; powershell -ExecutionPolicy Bypass -File deploy/scripts/make_pg_seed.ps1
#
# pg_dump writes with -f (never through a PowerShell pipe, which re-encodes bytes), and the
# roles filter writes UTF-8 WITHOUT a BOM (psql refuses a BOM at the top of an init script).
param(
    [string]$PgBin = "C:\Program Files\PostgreSQL\17\bin",
    [string]$AdminUser = "postgres"
)
$ErrorActionPreference = "Stop"
if (-not $env:PGPASSWORD) { throw "Set PGPASSWORD to the postgres superuser password first." }

$out = "deploy/initdb"
New-Item -ItemType Directory -Force $out | Out-Null

& "$PgBin\pg_dumpall.exe" -U $AdminUser -h localhost --roles-only -f "$out\_roles_raw.sql"
if ($LASTEXITCODE -ne 0) { throw "pg_dumpall failed" }
$kept = Get-Content "$out\_roles_raw.sql" | Where-Object {
    ($_ -match '^(CREATE|ALTER) ROLE (rain_app|insights_)') -or ($_ -match '^GRANT .* TO rain_app')
}
$lines = @("-- generated by deploy/scripts/make_pg_seed.ps1 -- roles for the rain stack") + $kept
[IO.File]::WriteAllLines((Join-Path (Get-Location) "$out\01-roles.sql"), $lines)  # UTF-8, no BOM
Remove-Item "$out\_roles_raw.sql"

& "$PgBin\pg_dump.exe" -U $AdminUser -h localhost -d rain --no-owner --encoding=UTF8 -f "$out\02-rain.sql"
if ($LASTEXITCODE -ne 0) { throw "pg_dump failed" }

# The PRD v0.3 wave's own database (rain_v3): --create emits CREATE DATABASE + its ACL
# (CONNECT for rain_app) and reconnects, so it seeds as 03 after the rain db. The host
# pg_dump bakes the Windows locale into CREATE DATABASE, which the Linux container
# rejects — rewrite it to encoding-only (template0 default locale).
& "$PgBin\pg_dump.exe" -U $AdminUser -h localhost -d rain_v3 --create --no-owner --encoding=UTF8 -f "$out\03-rain-v3.sql"
if ($LASTEXITCODE -ne 0) { throw "pg_dump rain_v3 failed" }
$v3 = Get-Content "$out\03-rain-v3.sql"
$v3 = $v3 -replace "^CREATE DATABASE rain_v3 .*$", "CREATE DATABASE rain_v3 WITH TEMPLATE = template0 ENCODING = 'UTF8';"
[IO.File]::WriteAllLines((Join-Path (Get-Location) "$out\03-rain-v3.sql"), $v3)  # UTF-8, no BOM

Write-Host "Wrote $out\01-roles.sql, $out\02-rain.sql and $out\03-rain-v3.sql"
